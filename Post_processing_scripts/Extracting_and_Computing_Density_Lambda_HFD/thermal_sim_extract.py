import numpy as np
import pandas as pd

#DIR_INDEX_reshape_HFD

# >>>>>>>>>>>>>>>>>> computed par atom temp profile <<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<

temp_profile = pd.read_csv("temp_profile.DIR_INDEX_reshape_HFD.0.0035", header=None)
temp_profile = temp_profile.iloc[3:,-1]
temp_profile_numpy = np.array(temp_profile)

num_heat_layers = 20
num_columns = int(num_heat_layers + 1)
num_rows = int(len(temp_profile_numpy)/num_columns)

temp_profile_numpy_split = np.array_split(temp_profile_numpy, num_rows)
temp_profile_numpy_reshaped = np.hstack(temp_profile_numpy_split).reshape((num_rows, num_columns))
temp_profile_numpy_reshaped = temp_profile_numpy_reshaped[:,1:].flatten()

split_temp_profile = np.array([line.split() for line in temp_profile_numpy_reshaped])
temp_profile_df = pd.DataFrame(split_temp_profile)
temp_profile_df = temp_profile_df.astype(float)

extracted_temp_profile = temp_profile_df.iloc[:,-1]
extracted_temp_profile = np.array(extracted_temp_profile)

np.savetxt("ext_final_temp_profile_DIR_INDEX_thermalcond.txt", extracted_temp_profile)




